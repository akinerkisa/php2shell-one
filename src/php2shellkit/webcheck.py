"""Opt-in single-target benign HEAD metadata probe, never an exploit scanner."""
from __future__ import annotations

from urllib.parse import urlsplit
from urllib.request import Request, build_opener, HTTPHandler, HTTPSHandler, HTTPRedirectHandler
from urllib.error import HTTPError, URLError
import re
import ssl

from patchproof.policy import upstream_check
from .common import envelope

class NoRedirect(HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        return None


def web_head(url: str, authorized: bool, timeout: float = 5.0) -> dict:
    if not authorized:
        raise ValueError('Remote requests require --authorized for assets you own or are permitted to assess')
    target = urlsplit(url)
    if target.scheme not in {'http', 'https'} or not target.hostname or target.username or target.password:
        raise ValueError('A valid http(s) URL without credentials is required')
    if not 0.5 <= timeout <= 15:
        raise ValueError('timeout must be between 0.5 and 15 seconds')
    req = Request(url, method='HEAD', headers={'User-Agent': 'PHP2Shell-One/0.4 authorized-inventory'})
    opener = build_opener(HTTPHandler(), HTTPSHandler(context=ssl.create_default_context()), NoRedirect())
    try:
        with opener.open(req, timeout=timeout) as resp:
            code = resp.status
            headers = dict(resp.headers.items())
    except HTTPError as exc:
        code = exc.code
        headers = dict(exc.headers.items())
    except URLError as exc:
        raise RuntimeError('HEAD request failed: ' + str(exc.reason)) from exc
    findings = []
    powered = next((v for k, v in headers.items() if k.lower() == 'x-powered-by'), '')
    match = re.search(r'PHP/(\d+\.\d+\.\d+)', powered, re.I)
    if match:
        version = match.group(1)
        outcome = upstream_check(version)
        verdict = outcome['status']
        findings.append({'severity': 'info', 'rule_id': 'DISCLOSED_PHP_VERSION', 'source': target.hostname,
            'message': f'X-Powered-By reports PHP/{version} ({verdict}); unauthenticated headers cannot attest actual runtime',
            'evidence': 'PHP/' + version})
    else:
        findings.append({'severity': 'info', 'rule_id': 'NO_PHP_VERSION', 'source': target.hostname,
            'message': 'PHP version not disclosed; absence of header proves nothing'})
    if target.scheme == 'http':
        findings.append({'severity': 'low', 'rule_id': 'INSECURE_HTTP', 'source': target.hostname,
            'message': 'Request used plaintext HTTP; prefer HTTPS when available'})
    findings.append({'severity': 'info', 'rule_id': 'HTTP_STATUS', 'source': target.hostname,
        'message': f'HEAD request returned HTTP {code}; no exploit or POST was sent'})
    return envelope('webcheck', findings, notes=[
        'Only one explicitly authorized HEAD request; no redirects, no request body, no brute-force.',
        'HTTP headers can be hidden, spoofed or generated by a proxy. NEVER treat this as a patch or vulnerability verdict.',
        'Only local/package/runtime evidence can establish a defensible version assessment.'])
